//! The toolchain's own copy of `solana-compiler-builtins`.
//!
//! `solana-compiler-builtins` is not a library the application depends on; it
//! is part of the SBPF toolchain, the same way `compiler_builtins` is part of
//! the Rust sysroot. So `cargo build-sbpf` builds it itself, caches the
//! result, and puts the artifact at the front of the link line. It never
//! appears in the application's Cargo dependency graph, and the application's
//! `Cargo.toml` is never touched.
//!
//! It is built the same way an application would build it: a small library
//! package with `solana-compiler-builtins` in its `[dependencies]` and
//! `use solana_compiler_builtins as _;` in its `lib.rs`. That package is
//! generated into the cache directory, so there is no checkout to keep in sync
//! and no bespoke build of our own.
//!
//! There is deliberately no way to point this at a local checkout. To work on
//! `solana-compiler-builtins` itself, add it to a test program as an ordinary
//! Cargo dependency: a strong definition from the application or one of its
//! dependencies already takes precedence over the toolchain's fallback, so the
//! local copy wins without the toolchain needing to know about it.
//!
//! The artifact is the dependency's `.rlib` out of that package's `deps/`. On
//! SBPF, rustc's target spec sets `obj-is-bitcode`, so the "object" files
//! inside an rlib are already LLVM bitcode -- exactly what `sbpf-linker`
//! consumes. An `.a` would hold the same bitcode members with the metadata
//! stripped, which buys nothing, and a bare `.bc` would lose the archive
//! structure for no reason.

use std::{
    collections::hash_map::DefaultHasher,
    env,
    ffi::{OsStr, OsString},
    fs,
    hash::{Hash as _, Hasher as _},
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

use anyhow::{bail, Context, Result};

use crate::config::{BuildConfig, SbpfArch};

const CRATE: &str = "solana-compiler-builtins";

/// Where to get the builtins, and how to build them.
///
/// `features = ["weak-linkage"]` is the load-bearing part: it is what declares
/// the builtins `weak_odr`, and `weak_odr` is what lets an application replace
/// one by defining the same symbol. Without it they are strong and the link
/// fails with `symbol multiply defined` against any such application.
///
/// Asking for the feature by name also means a crate too old to have it fails
/// at resolution, with a message naming the missing feature, rather than
/// quietly building strong symbols.
const DEPENDENCY: &str =
    "{ version = \"^0.2\", features = [\"weak-linkage\"] }";

/// Point this at a directory to relocate the generated package and the
/// artifact cache.
const CACHE_ENV: &str = "SBPF_COMPILER_BUILTINS_CACHE";

/// Resolves the compiler-builtins artifact for `build_config`, building it
/// first if the cache has no compatible copy.
pub(crate) fn ensure(
    cargo: &OsStr,
    build_config: &BuildConfig,
) -> Result<PathBuf> {
    let root = cache_root()?;
    let package = generate_package(&root)?;

    let rustflags = rustflags(build_config);
    let (version, identity) = resolve_identity(cargo, &package)?;
    let key = cache_key(&rustflags, &version, &identity)?;

    let cache = root.join(&key);
    let artifact = cache.join("libsolana_compiler_builtins.rlib");
    if artifact.is_file() {
        return Ok(artifact);
    }

    eprintln!("building {CRATE} {identity} for the SBPF toolchain");
    build(cargo, &package, &cache, &rustflags)?;

    if !artifact.is_file() {
        bail!("built {CRATE} but no rlib landed in {}", cache.display());
    }
    Ok(artifact)
}

/// Writes the library package that depends on the builtins, and returns its
/// directory. Rewritten only when the contents would change, so Cargo's
/// fingerprints survive between builds.
fn generate_package(root: &Path) -> Result<PathBuf> {
    let package = root.join("builtins-package");
    fs::create_dir_all(package.join("src"))
        .with_context(|| format!("failed to create {}", package.display()))?;

    let manifest = format!(
        "# Generated by cargo-build-sbpf. Edits will be overwritten.\n\
         #\n\
         # This package exists only to build `{CRATE}` the same way an\n\
         # application would, so the toolchain can hand the resulting rlib to\n\
         # sbpf-linker. Nothing links against this package itself.\n\
         [package]\n\
         name = \"sbpf-compiler-builtins\"\n\
         version = \"0.0.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\
         \n\
         [dependencies]\n\
         {CRATE} = {DEPENDENCY}\n\
         \n\
         # Spelled out rather than left to Cargo's release defaults, whose\n\
         # panic strategy is `unwind`. The rustflags set the same things, and\n\
         # win on ordering, so this is belt-and-braces -- but it keeps the\n\
         # package self-describing instead of depending on flag precedence.\n\
         # Dropping it leaves the code and every symbol identical and only\n\
         # changes the crate metadata hash, so it is safe to drop; it is kept\n\
         # for legibility, not correctness.\n\
         [profile.release]\n\
         opt-level = 3\n\
         panic = \"abort\"\n\
         \n\
         [workspace]\n"
    );
    let lib = format!(
        "// Generated by cargo-build-sbpf. Edits will be overwritten.\n\
         //\n\
         // The `use` is the point: it makes `{CRATE}` a crate rustc links in\n\
         // rather than an unused dependency.\n\
         #![no_std]\n\
         \n\
         use solana_compiler_builtins as _;\n"
    );

    if write_if_changed(&package.join("Cargo.toml"), &manifest)? {
        // The manifest asks for something different than it did last time, so
        // whatever the lockfile resolved to no longer answers the question.
        // Dropping it makes `resolve_identity` resolve again; keeping it would
        // key the cache on the previous dependency and hand back its artifact.
        let lock = package.join("Cargo.lock");
        if lock.is_file() {
            fs::remove_file(&lock).with_context(|| {
                format!("failed to remove {}", lock.display())
            })?;
        }
    }
    write_if_changed(&package.join("src/lib.rs"), &lib)?;
    Ok(package)
}

/// Writes `contents` unless they are already there, reporting whether the file
/// on disk changed.
fn write_if_changed(path: &Path, contents: &str) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
        return Ok(false);
    }
    fs::write(path, contents)
        .with_context(|| format!("failed to write {}", path.display()))?;
    Ok(true)
}

/// What Cargo resolved the builtins to, read out of the generated package's
/// lockfile: the version, and the full identity including the git commit.
///
/// The source matters, not just the version: a git branch moves while its
/// version stays put, so the version alone would let a stale artifact be
/// reused. The lockfile is kept, so the choice is made once and then stays put
/// rather than drifting build to build; it is discarded when the manifest
/// changes, and removing the cache directory picks up a newer release.
fn resolve_identity(
    cargo: &OsStr,
    package: &Path,
) -> Result<(String, String)> {
    let lock = package.join("Cargo.lock");
    if !lock.is_file() {
        let status = Command::new(cargo)
            .arg("+nightly")
            .arg("generate-lockfile")
            .arg("--manifest-path")
            .arg(package.join("Cargo.toml"))
            .stdout(Stdio::inherit())
            .stderr(Stdio::inherit())
            .status()
            .with_context(|| format!("failed to resolve {CRATE}"))?;
        if !status.success() {
            bail!("resolving {CRATE} failed with status {status}");
        }
    }

    let contents = fs::read_to_string(&lock)
        .with_context(|| format!("failed to read {}", lock.display()))?;
    // The lockfile is a sequence of `[[package]]` tables; find ours and take
    // the `version` and `source` that follow its `name`.
    let mut lines = contents.lines();
    while let Some(line) = lines.next() {
        if line.trim() != format!("name = \"{CRATE}\"") {
            continue;
        }
        let mut version = None;
        let mut source = String::new();
        for line in lines.by_ref().take(3) {
            let line = line.trim();
            if let Some(value) = line.strip_prefix("version = ") {
                version = Some(value.trim_matches('"').to_string());
            } else if let Some(value) = line.strip_prefix("source = ") {
                source = value.trim_matches('"').to_string();
            }
        }
        let version = version.with_context(|| {
            format!("{CRATE} has no version in {}", lock.display())
        })?;
        return Ok((version.clone(), format!("{version} {source}")));
    }
    bail!("{CRATE} is not in {}", lock.display())
}

/// The codegen settings the artifact is built with. They have to match the
/// application's target: the same SBPF architecture and CPU, the same target
/// features, the same panic strategy, the same relocation model.
///
/// Every one of these ends up in the cache key, so changing any of them
/// produces a different artifact rather than reusing an incompatible one.
fn rustflags(build_config: &BuildConfig) -> Vec<String> {
    let cpu = match build_config.arch {
        SbpfArch::V0 => "v2",
        SbpfArch::V3 => "v4",
    };
    [
        "-C",
        "opt-level=3",
        "-C",
        "panic=abort",
        "-C",
        "relocation-model=static",
        "-C",
        &format!("target-cpu={cpu}"),
        "-C",
        "target-feature=+allows-misaligned-mem-access",
        "--cfg=target_os=\"solana\"",
        "--cfg=target_feature=\"static-syscalls\"",
        "-A",
        "explicit_builtin_cfgs_in_flags",
    ]
    .into_iter()
    .map(str::to_string)
    .collect()
}

/// The cache key covers everything that can change the bitcode: which release
/// of the crate, which compiler, and the codegen settings.
///
/// `DefaultHasher` is not stable across Rust releases, which is fine here --
/// an unstable hash costs one rebuild, never a wrong artifact -- and the
/// version of this tool is part of the key anyway.
fn cache_key(
    rustflags: &[String],
    version: &str,
    identity: &str,
) -> Result<String> {
    let mut hasher = DefaultHasher::new();
    env!("CARGO_PKG_VERSION").hash(&mut hasher);
    rustflags.hash(&mut hasher);
    identity.hash(&mut hasher);

    let output = Command::new("rustup")
        .args(["run", "nightly", "rustc", "-vV"])
        .output()
        .context("failed to read the nightly rustc version")?;
    if !output.status.success() {
        bail!("`rustup run nightly rustc -vV` failed");
    }
    output.stdout.hash(&mut hasher);

    Ok(format!("{version}-{:016x}", hasher.finish()))
}

fn cache_root() -> Result<PathBuf> {
    if let Some(dir) = env::var_os(CACHE_ENV) {
        return Ok(PathBuf::from(dir));
    }
    Ok(home::cargo_home()
        .context("failed to locate CARGO_HOME")?
        .join("sbpf-compiler-builtins"))
}

/// Builds the package into `cache` and keeps the dependency's rlib.
fn build(
    cargo: &OsStr,
    package: &Path,
    cache: &Path,
    rustflags: &[String],
) -> Result<()> {
    let target_dir = cache.join("target");
    fs::create_dir_all(&target_dir).with_context(|| {
        format!("failed to create {}", target_dir.display())
    })?;

    let status = Command::new(cargo)
        .arg("+nightly")
        .arg("build")
        .arg("--release")
        .arg("--lib")
        .arg("--target")
        .arg("bpfel-unknown-none")
        .arg("-Z")
        .arg("build-std=core,alloc")
        .arg("--manifest-path")
        .arg(package.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir)
        // The application's Cargo config has nothing to do with this build, so
        // the flags go through the environment, which outranks any config file
        // Cargo might discover next to the generated package.
        .env("CARGO_TARGET_BPFEL_UNKNOWN_NONE_RUSTFLAGS", rustflags.join(" "))
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit())
        .status()
        .with_context(|| format!("failed to build {CRATE}"))?;
    if !status.success() {
        bail!("building {CRATE} failed with status {status}");
    }

    // The package itself holds nothing; what the linker needs is the
    // dependency's rlib, with the builtins' bitcode in it.
    let deps = target_dir.join("bpfel-unknown-none/release/deps");
    let rlib = fs::read_dir(&deps)
        .with_context(|| format!("failed to read {}", deps.display()))?
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            let name = path.file_name()?.to_str()?;
            (name.starts_with("libsolana_compiler_builtins")
                && name.ends_with(".rlib"))
            .then_some(path)
        })
        .next()
        .with_context(|| format!("no {CRATE} rlib in {}", deps.display()))?;

    let artifact = cache.join("libsolana_compiler_builtins.rlib");
    fs::copy(&rlib, &artifact).with_context(|| {
        format!("failed to copy {} to {}", rlib.display(), artifact.display())
    })?;
    Ok(())
}

/// The rustc flags that put the artifact on the link line, ahead of
/// everything rustc passes itself.
///
/// `-Z pre-link-arg` and not `-C link-arg`, because the latter *appends*: the
/// rlib would land after `libcompiler_builtins.rlib`, and since both declare
/// these symbols weakly, LLVM would keep `compiler_builtins`' copies and
/// quietly ignore ours. Prepending puts ours first, which is what makes them
/// win -- while still losing to an application that defines a builtin itself.
pub(crate) fn pre_link_args(artifact: &Path) -> [OsString; 2] {
    let mut arg = OsString::from("pre-link-arg=");
    arg.push(artifact);
    [OsString::from("-Z"), arg]
}
