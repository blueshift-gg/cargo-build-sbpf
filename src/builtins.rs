//! The toolchain's own copy of `solana-compiler-builtins`.
//!
//! `solana-compiler-builtins` is not a library the application depends on; it
//! is part of the SBPF toolchain, the same way `compiler_builtins` is part of
//! the Rust sysroot. So `cargo build-sbpf` builds it itself, caches the
//! result, and puts the artifact at the front of the link line. It never
//! appears in the application's Cargo dependency graph, and the application's
//! `Cargo.toml` is never touched.
//!
//! It is built the same way an application would build it: a small library
//! package with `solana-compiler-builtins` in its `[dependencies]` and
//! `use solana_compiler_builtins as _;` in its `lib.rs`. That package is
//! generated into the cache directory, so there is no checkout to keep in sync
//! and no bespoke build of our own.
//!
//! There is deliberately no way to point this at a local checkout. To work on
//! `solana-compiler-builtins` itself, add it to a test program as an ordinary
//! Cargo dependency: a strong definition from the application or one of its
//! dependencies already takes precedence over the toolchain's fallback, so the
//! local copy wins without the toolchain needing to know about it.
//!
//! The artifact is the dependency's `.rlib`, reported by cargo's `compiler-artifact`
//! message. On SBPF, rustc's target spec sets `obj-is-bitcode`, so the "object" files
//! inside an rlib are already LLVM bitcode -- exactly what `sbpf-linker`
//! consumes. An `.a` would hold the same bitcode members with the metadata
//! stripped, which buys nothing, and a bare `.bc` would lose the archive
//! structure for no reason.

use std::{
    collections::hash_map::DefaultHasher,
    env,
    ffi::{OsStr, OsString},
    fs,
    hash::{Hash as _, Hasher as _},
    io::BufReader,
    path::{Path, PathBuf},
    process::{Command, Stdio},
};

use anyhow::{bail, Context, Result};
use cargo_metadata::{Message, MetadataCommand};
use serde::Deserialize;

use crate::config::{BuildConfig, SbpfArch};

const CRATE: &str = "solana-compiler-builtins";

/// Where to get the builtins, and how to build them.
///
/// `features = ["weak-linkage"]` is the load-bearing part: it is what declares
/// the builtins `weak_odr`, and `weak_odr` is what lets an application replace
/// one by defining the same symbol. Without it they are strong and the link
/// fails with `symbol multiply defined` against any such application.
///
/// Asking for the feature by name also means a crate too old to have it fails
/// at resolution, with a message naming the missing feature, rather than
/// quietly building strong symbols.
const DEPENDENCY: &str =
    "{ version = \"^0.2\", features = [\"weak-linkage\"] }";

/// Point this at a directory to relocate the generated package and the
/// artifact cache.
const CACHE_ENV: &str = "SBPF_COMPILER_BUILTINS_CACHE";

/// Resolves the compiler-builtins artifact for `build_config`, building it
/// first if the cache has no compatible copy.
pub(crate) fn ensure(
    cargo: &OsStr,
    build_config: &BuildConfig,
    cargo_args: &[OsString],
) -> Result<PathBuf> {
    let root = cache_root()?;
    let package = generate_package(&root)?;

    let profile = std_profile(cargo, cargo_args)?;
    let project = project_rustflags(cargo, cargo_args)?;
    let rustflags = rustflags(build_config, &profile, &project);
    let (version, identity) = resolve_identity(cargo, &package, cargo_args)?;
    let key = cache_key(&rustflags, &version, &identity)?;

    let cache = root.join(&key);
    let artifact = cache.join("libsolana_compiler_builtins.rlib");
    if artifact.is_file() {
        return Ok(artifact);
    }

    eprintln!("building {CRATE} {identity} for the SBPF toolchain");
    build(cargo, &package, &cache, &rustflags)?;

    if !artifact.is_file() {
        bail!("built {CRATE} but no rlib landed in {}", cache.display());
    }
    Ok(artifact)
}

/// Writes the library package that depends on the builtins, and returns its
/// directory. Rewritten only when the contents would change, so Cargo's
/// fingerprints survive between builds.
fn generate_package(root: &Path) -> Result<PathBuf> {
    let package = root.join("builtins-package");
    fs::create_dir_all(package.join("src"))
        .with_context(|| format!("failed to create {}", package.display()))?;

    let manifest = format!(
        "# Generated by cargo-build-sbpf. Edits will be overwritten.\n\
         #\n\
         # This package exists only to build `{CRATE}` the same way an\n\
         # application would, so the toolchain can hand the resulting rlib to\n\
         # sbpf-linker. Nothing links against this package itself.\n\
         [package]\n\
         name = \"sbpf-compiler-builtins\"\n\
         version = \"0.0.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\
         \n\
         [dependencies]\n\
         {CRATE} = {DEPENDENCY}\n\
         \n\
         # Spelled out rather than left to Cargo's release defaults, whose\n\
         # panic strategy is `unwind`. The rustflags set the same things, and\n\
         # win on ordering, so this is belt-and-braces -- but it keeps the\n\
         # package self-describing instead of depending on flag precedence.\n\
         # Dropping it leaves the code and every symbol identical and only\n\
         # changes the crate metadata hash, so it is safe to drop; it is kept\n\
         # for legibility, not correctness.\n\
         [profile.release]\n\
         opt-level = 3\n\
         panic = \"abort\"\n\
         \n\
         [workspace]\n"
    );
    let lib = format!(
        "// Generated by cargo-build-sbpf. Edits will be overwritten.\n\
         //\n\
         // The `use` is the point: it makes `{CRATE}` a crate rustc links in\n\
         // rather than an unused dependency.\n\
         #![no_std]\n\
         \n\
         use solana_compiler_builtins as _;\n"
    );

    write_if_changed(&package.join("Cargo.toml"), &manifest)?;
    write_if_changed(&package.join("src/lib.rs"), &lib)?;
    Ok(package)
}

/// Writes `contents` unless they are already there, reporting whether the file
/// on disk changed.
fn write_if_changed(path: &Path, contents: &str) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
        return Ok(false);
    }
    fs::write(path, contents)
        .with_context(|| format!("failed to write {}", path.display()))?;
    Ok(true)
}

/// What Cargo resolved the builtins to: the version, and the package id.
/// The id pins where the builtins came from and at what version, so a
/// dependency change changes the cache key. `cargo metadata` resolves the
/// manifest and reports both, and keeps the lockfile in sync, so removing
/// the cache directory picks up a newer release.
fn resolve_identity(
    cargo: &OsStr,
    package: &Path,
    cargo_args: &[OsString],
) -> Result<(String, String)> {
    let metadata = MetadataCommand::new()
        .cargo_path(cargo)
        .env("RUSTUP_TOOLCHAIN", "nightly")
        .manifest_path(package.join("Cargo.toml"))
        .other_options(config_args(cargo_args))
        .exec()
        .with_context(|| format!("failed to resolve {CRATE}"))?;
    let package = metadata
        .packages
        .into_iter()
        .find(|package| package.name == CRATE)
        .with_context(|| format!("{CRATE} is not in the dependency graph"))?;
    let version = package.version.to_string();
    Ok((version, package.id.repr))
}

/// The arguments forwarded to `cargo build` that are Cargo configuration:
/// `--config` and offline mode. `--frozen` also demands an up-to-date
/// lockfile, which the generated package lacks on a first run, so only its
/// offline half applies.
///
/// Resolving the builtins and reading the project's rustflags take these, so
/// both see the configuration the program's own build does. The builtins
/// build does not: a forwarded `--config` can also set profile options that
/// would change the artifact without changing its cache key.
fn config_args(cargo_args: &[OsString]) -> Vec<String> {
    let mut resolve = Vec::new();
    let mut args = cargo_args.iter().filter_map(|arg| arg.to_str());
    while let Some(arg) = args.next() {
        match arg {
            "--offline" | "--frozen" => resolve.push("--offline".to_string()),
            "--config" => resolve.extend(
                args.next().map(|config| format!("--config={config}")),
            ),
            _ if arg.starts_with("--config=") => resolve.push(arg.to_string()),
            _ => {}
        }
    }
    resolve
}

/// The profile settings Cargo gives the standard library's `compiler_builtins`
/// in this build. `-Zbuild-std` builds the standard library with the project's
/// profile, so Rust's own builtins get the project's overflow checks, debug
/// assertions and so on; these builtins follow the same settings.
#[derive(Deserialize)]
struct Profile {
    opt_level: String,
    overflow_checks: bool,
    debug_assertions: bool,
    debuginfo: serde_json::Value,
}

#[derive(Deserialize)]
struct UnitGraph {
    units: Vec<Unit>,
}

#[derive(Deserialize)]
struct Unit {
    #[serde(default)]
    is_std: bool,
    target: UnitTarget,
    profile: Profile,
}

#[derive(Deserialize)]
struct UnitTarget {
    name: String,
}

/// Reads that profile from Cargo's unit graph for the same build, including
/// the arguments forwarded to `cargo build`, so `Cargo.toml`, Cargo config,
/// `CARGO_PROFILE_*` and `--profile` all count. Nothing is built.
fn std_profile(cargo: &OsStr, cargo_args: &[OsString]) -> Result<Profile> {
    let output = Command::new(cargo)
        .arg("+nightly")
        .arg("build")
        .arg("--release")
        .arg("--target")
        .arg("bpfel-unknown-none")
        .arg("-Z")
        .arg("build-std=core,alloc")
        .arg("-Z")
        .arg("unstable-options")
        .arg("--unit-graph")
        .args(cargo_args)
        .output()
        .context("failed to read Cargo's unit graph")?;
    if !output.status.success() {
        bail!(
            "reading Cargo's unit graph failed with status {}:\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    parse_std_profile(&output.stdout)
}

fn parse_std_profile(unit_graph: &[u8]) -> Result<Profile> {
    let graph: UnitGraph = serde_json::from_slice(unit_graph)
        .context("failed to parse Cargo's unit graph")?;
    graph
        .units
        .into_iter()
        .find(|unit| unit.is_std && unit.target.name == "compiler_builtins")
        .map(|unit| unit.profile)
        .context("Cargo's unit graph has no standard `compiler_builtins`")
}

/// The project's rustflags for the target, merged the way the program's build
/// gets them: from Cargo config, `CARGO_TARGET_BPFEL_UNKNOWN_NONE_RUSTFLAGS`
/// and forwarded `--config`. Under `-Zbuild-std` they reach Rust's own
/// `compiler_builtins` too. `RUSTFLAGS` is rejected before this runs.
fn project_rustflags(
    cargo: &OsStr,
    cargo_args: &[OsString],
) -> Result<Vec<String>> {
    const KEY: &str = "target.bpfel-unknown-none.rustflags";
    let output = Command::new(cargo)
        .args(["+nightly", "-Z", "unstable-options", "config", "get"])
        .args(["--format", "json-value"])
        .args(config_args(cargo_args))
        .arg(KEY)
        .output()
        .context("failed to read the project's rustflags")?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        // Cargo reports a key nothing sets as an error.
        if stderr.contains("is not set") {
            return Ok(Vec::new());
        }
        bail!(
            "reading `{KEY}` failed with status {}:\n{}",
            output.status,
            stderr.trim()
        );
    }
    // An array, or a string, which Cargo splits on whitespace.
    Ok(
        match serde_json::from_slice(&output.stdout)
            .with_context(|| format!("failed to parse `{KEY}`"))?
        {
            serde_json::Value::String(flags) => {
                flags.split_whitespace().map(str::to_string).collect()
            }
            flags => serde_json::from_value(flags)
                .with_context(|| format!("unexpected `{KEY}`"))?,
        },
    )
}

/// The codegen settings the artifact is built with. The SBPF architecture and
/// CPU, the target features and the relocation model have to match the
/// application's target; the rest follows `profile` and the project's
/// rustflags. They come in the order Cargo gives the standard library in the
/// program's build: the profile, then the project's rustflags, then the SBPF
/// settings, so the project's rustflags override its profile and the SBPF
/// settings override both.
///
/// The panic strategy is `immediate-abort`. With `abort`, a failed overflow
/// check or debug assertion calls `core`'s panic functions, and those calls
/// name the `core` built here, not the application's, so the link fails. With
/// `immediate-abort` it traps in place, which is what rustc does for Rust's own
/// `compiler_builtins`.
///
/// Every one of these ends up in the cache key, so changing any of them
/// produces a different artifact rather than reusing an incompatible one.
fn rustflags(
    build_config: &BuildConfig,
    profile: &Profile,
    project: &[String],
) -> Vec<String> {
    let cpu = match build_config.arch {
        SbpfArch::V0 => "v2",
        SbpfArch::V3 => "v4",
    };
    let on_off = |enabled: bool| if enabled { "on" } else { "off" };
    let debuginfo = match &profile.debuginfo {
        serde_json::Value::String(level) => level.clone(),
        level => level.to_string(),
    };
    let mut flags: Vec<String> = [
        "-C",
        &format!("opt-level={}", profile.opt_level),
        "-C",
        &format!("overflow-checks={}", on_off(profile.overflow_checks)),
        "-C",
        &format!("debug-assertions={}", on_off(profile.debug_assertions)),
        "-C",
        &format!("debuginfo={debuginfo}"),
    ]
    .into_iter()
    .map(str::to_string)
    .collect();
    flags.extend_from_slice(project);
    flags.extend(
        [
            "-Z",
            "unstable-options",
            "-C",
            "panic=immediate-abort",
            "-C",
            "relocation-model=static",
            "-C",
            &format!("target-cpu={cpu}"),
            "-Z",
            "llvm-target-feature=+allows-misaligned-mem-access",
            "--cfg=target_os=\"solana\"",
            "--cfg=target_feature=\"static-syscalls\"",
            "-A",
            "explicit_builtin_cfgs_in_flags",
        ]
        .into_iter()
        .map(str::to_string),
    );
    flags
}

/// The cache key covers everything that can change the bitcode: which release
/// of the crate, which compiler, and the codegen settings.
///
/// `DefaultHasher` is not stable across Rust releases, which is fine here --
/// an unstable hash costs one rebuild, never a wrong artifact -- and the
/// version of this tool is part of the key anyway.
fn cache_key(
    rustflags: &[String],
    version: &str,
    identity: &str,
) -> Result<String> {
    let mut hasher = DefaultHasher::new();
    env!("CARGO_PKG_VERSION").hash(&mut hasher);
    rustflags.hash(&mut hasher);
    identity.hash(&mut hasher);

    let output = Command::new("rustup")
        .args(["run", "nightly", "rustc", "-vV"])
        .output()
        .context("failed to read the nightly rustc version")?;
    if !output.status.success() {
        bail!("`rustup run nightly rustc -vV` failed");
    }
    output.stdout.hash(&mut hasher);

    Ok(format!("{version}-{:016x}", hasher.finish()))
}

fn cache_root() -> Result<PathBuf> {
    if let Some(dir) = env::var_os(CACHE_ENV) {
        return Ok(PathBuf::from(dir));
    }
    Ok(home::cargo_home()
        .context("failed to locate CARGO_HOME")?
        .join("sbpf-compiler-builtins"))
}

/// Builds the package into `cache` and keeps the dependency's rlib.
fn build(
    cargo: &OsStr,
    package: &Path,
    cache: &Path,
    rustflags: &[String],
) -> Result<()> {
    let target_dir = cache.join("target");
    fs::create_dir_all(&target_dir).with_context(|| {
        format!("failed to create {}", target_dir.display())
    })?;

    let mut child = Command::new(cargo)
        .arg("+nightly")
        .arg("build")
        .arg("--release")
        .arg("--lib")
        .arg("--target")
        .arg("bpfel-unknown-none")
        .arg("-Z")
        .arg("build-std=core,alloc")
        .arg("--message-format=json-render-diagnostics")
        .arg("--manifest-path")
        .arg(package.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir)
        // The artifact is cached under these flags, so it is built with exactly
        // them: `CARGO_ENCODED_RUSTFLAGS` outranks `RUSTFLAGS` and the rustflags
        // of any Cargo config, and the profile settings in it come after the
        // ones Cargo derives from a profile, so they win too.
        .env("CARGO_ENCODED_RUSTFLAGS", rustflags.join("\x1f"))
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .with_context(|| format!("failed to build {CRATE}"))?;

    let stdout =
        child.stdout.take().context("failed to pipe cargo's stdout")?;
    let rlib = Message::parse_stream(BufReader::new(stdout))
        .filter_map(|message| match message.ok()? {
            Message::CompilerArtifact(artifact)
                if artifact.target.name == "solana_compiler_builtins" =>
            {
                artifact
                    .filenames
                    .into_iter()
                    .find(|filename| filename.extension() == Some("rlib"))
            }
            _ => None,
        })
        .last();

    let status = child.wait()?;
    if !status.success() {
        bail!("building {CRATE} failed with status {status}");
    }
    // The package itself holds nothing; what the linker needs is the
    // dependency's rlib, with the builtins' bitcode in it.
    let rlib = rlib
        .with_context(|| format!("cargo built {CRATE} but no rlib found"))?;

    let artifact = cache.join("libsolana_compiler_builtins.rlib");
    fs::copy(&rlib, &artifact).with_context(|| {
        format!("failed to copy {rlib} to {}", artifact.display())
    })?;
    Ok(())
}

/// The rustc flags that put the artifact on the link line, ahead of
/// everything rustc passes itself.
///
/// `-Z pre-link-arg` and not `-C link-arg`, because the latter *appends*: the
/// rlib would land after `libcompiler_builtins.rlib`, and since both declare
/// these symbols weakly, LLVM would keep `compiler_builtins`' copies and
/// quietly ignore ours. Prepending puts ours first, which is what makes them
/// win -- while still losing to an application that defines a builtin itself.
pub(crate) fn pre_link_args(artifact: &Path) -> [OsString; 2] {
    let mut arg = OsString::from("pre-link-arg=");
    arg.push(artifact);
    [OsString::from("-Z"), arg]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn forwards_offline_mode_and_config() {
        let args = [
            "--locked",
            "--offline",
            "--frozen",
            "--config",
            "net.offline=true",
            "-p",
            "program",
            "--config=extra.toml",
        ]
        .map(OsString::from);
        assert_eq!(
            config_args(&args),
            [
                "--offline",
                "--offline",
                "--config=net.offline=true",
                "--config=extra.toml",
            ]
        );
    }

    #[test]
    fn follows_the_standard_librarys_profile_and_rustflags() {
        // A project crate may also be called `compiler_builtins`; only the
        // standard library's counts.
        let unit_graph = br#"{"version": 1, "roots": [], "units": [
            {"is_std": true, "target": {"name": "core"},
             "profile": {"opt_level": "3", "overflow_checks": false,
                         "debug_assertions": false, "debuginfo": 0}},
            {"target": {"name": "compiler_builtins"},
             "profile": {"opt_level": "0", "overflow_checks": false,
                         "debug_assertions": false, "debuginfo": 2}},
            {"is_std": true, "target": {"name": "compiler_builtins"},
             "profile": {"opt_level": "s", "overflow_checks": true,
                         "debug_assertions": true,
                         "debuginfo": "line-tables-only"}}
        ]}"#;
        let profile = parse_std_profile(unit_graph).unwrap();
        let project = ["-C", "overflow-checks=off", "-C", "target-cpu=v2"]
            .map(str::to_string);
        let flags = rustflags(
            &BuildConfig { arch: SbpfArch::V3, simd_0460: false },
            &profile,
            &project,
        );
        let position = |flag: &str| {
            flags
                .iter()
                .position(|f| f == flag)
                .unwrap_or_else(|| panic!("{flag} not in {flags:?}"))
        };
        for flag in [
            "opt-level=s",
            "debug-assertions=on",
            "debuginfo=line-tables-only",
            "panic=immediate-abort",
        ] {
            position(flag);
        }
        // The project's rustflags override its profile, and the SBPF settings
        // override the project's rustflags; rustc takes the last of each.
        assert!(
            position("overflow-checks=on") < position("overflow-checks=off")
        );
        assert!(position("target-cpu=v2") < position("target-cpu=v4"));
    }
}
